/**
  * @brief  Manage the CDC class requests
  * @param  cmd: Command code
  * @param  pbuf: Buffer containing command data (request parameters)
  * @param  length: Number of data to be sent (in bytes)
  * @retval Result of the operation: USBD_OK if all operations are OK else USBD_FAIL
  */
static int8_t CDC_Control_FS(uint8_t cmd, uint8_t* pbuf, uint16_t length)
{
  /* USER CODE BEGIN 5 */
  switch(cmd)
  {
    case CDC_SEND_ENCAPSULATED_COMMAND:

    break;

    case CDC_GET_ENCAPSULATED_RESPONSE:

    break;

    case CDC_SET_COMM_FEATURE:

    break;

    case CDC_GET_COMM_FEATURE:

    break;

    case CDC_CLEAR_COMM_FEATURE:

    break;

  /*******************************************************************************/
  /* Line Coding Structure                                                       */
  /*-----------------------------------------------------------------------------*/
  /* Offset | Field       | Size | Value  | Description                          */
  /* 0      | dwDTERate   |   4  | Number |Data terminal rate, in bits per second*/
  /* 4      | bCharFormat |   1  | Number | Stop bits                            */
  /*                                        0 - 1 Stop bit                       */
  /*                                        1 - 1.5 Stop bits                    */
  /*                                        2 - 2 Stop bits                      */
  /* 5      | bParityType |  1   | Number | Parity                               */
  /*                                        0 - None                             */
  /*                                        1 - Odd                              */
  /*                                        2 - Even                             */
  /*                                        3 - Mark                             */
  /*                                        4 - Space                            */
  /* 6      | bDataBits  |   1   | Number Data bits (5, 6, 7, 8 or 16).          */
  /*******************************************************************************/
    case CDC_SET_LINE_CODING:

    break;

    case CDC_GET_LINE_CODING:

    break;

    case CDC_SET_CONTROL_LINE_STATE:
      // pbuf[2] contains the DTR and RTS bits. Bit 0 is DTR.
      if (pbuf[2] & 0x01) {
          g_usb_host_connected = 1; // Host opened the COM port
      } else {
          g_usb_host_connected = 0; // Host closed the COM port
      }
    break;

    case CDC_SEND_BREAK:

    break;

  default:
    break;
  }

  return (USBD_OK);
  /* USER CODE END 5 */
}

/**
  * @brief  Data received over USB OUT endpoint are sent over CDC interface
  *         through this function.
  *
  *         @note
  *         This function will issue a NAK packet on any OUT packet received on
  *         USB endpoint until exiting this function. If you exit this function
  *         before transfer is complete on CDC interface (ie. using DMA controller)
  *         it will result in receiving more data while previous ones are still
  *         not sent.
  *
  * @param  Buf: Buffer of data to be received
  * @param  Len: Number of data received (in bytes)
  * @retval Result of the operation: USBD_OK if all operations are OK else USBD_FAIL
  */
static int8_t CDC_Receive_FS(uint8_t* Buf, uint32_t *Len)
{
  /* USER CODE BEGIN 6 */
  USBD_CDC_SetRxBuffer(&hUsbDeviceFS, &Buf[0]);
  USBD_CDC_ReceivePacket(&hUsbDeviceFS);
  
  // File Transfer Hook
  if (g_file_transfer_mode) {
      handle_file_transfer(Buf, *Len);
      return (USBD_OK);
  }
  
  // Initialize Binary Parser
  static uint8_t parser_initialized = 0;
  if (!parser_initialized) {
      BP_Init(&bp_parser, BP_Command_Callback);
      parser_initialized = 1;
  }
  
  if (g_rx_test_mode) {
        for (uint32_t i = 0; i < *Len; i++) {
            uint8_t current_byte = Buf[i];
            if (g_rx_test_last_byte == 0x03 && current_byte == 0x03) {
                g_rx_test_count++;
                g_rx_test_last_byte = 0;
            } else {
                g_rx_test_last_byte = current_byte;
            }
        }
        // Do not return here, so we can still receive STOP command
    }
    
    static uint8_t is_new_command = 1;
    
    for(uint32_t i = 0; i < *Len; i++) {
        uint8_t rx_byte = Buf[i];

        // 1. Feed Binary Parser
        BP_ProcessByte(&bp_parser, rx_byte);
        
        // 2. If Binary Parser is confident (past header), block ASCII
        // SYNC1/SYNC2 states are too common, don't block ASCII yet
        if (bp_parser.state >= BP_STATE_LEN1) {
            continue; 
        }

        // In test mode, ignore 0x03 to prevent buffer overflow
        if (g_rx_test_mode && rx_byte == 0x03) continue;
        
        if (rx_byte == '\r') {
            continue;
        }
      
      if (rx_byte == '\n') {
          usb_cmd_buffer[usb_cmd_index] = '\0'; 
          
          if (usb_cmd_index > 0) {
              usb_cmd_ready = 1;  
          }
          
          usb_cmd_index = 0;
          is_new_command = 1;  
      }
      else if (usb_cmd_index < sizeof(usb_cmd_buffer)-1) {
          usb_cmd_buffer[usb_cmd_index++] = rx_byte;
          is_new_command = 0;
      } 
  }
  
  return (USBD_OK);
  /* USER CODE END 6 */
}

/**
  * @brief  CDC_Transmit_FS
  *         Data to send over USB IN endpoint are sent over CDC interface
  *         through this function.
  *         @note
  *
  *
  * @param  Buf: Buffer of data to be sent
  * @param  Len: Number of data to be sent (in bytes)
  * @retval USBD_OK if all operations are OK else USBD_FAIL or USBD_BUSY
  */
uint8_t CDC_Transmit_FS(uint8_t* Buf, uint16_t Len)
{
  uint8_t result = USBD_OK;
  /* USER CODE BEGIN 7 */
  USBD_CDC_HandleTypeDef *hcdc = (USBD_CDC_HandleTypeDef*)hUsbDeviceFS.pClassData;
  
  if (hcdc->TxState != 0){
    return USBD_BUSY;
  }
  
  // FIX: Copy data to static buffer to prevent stack corruption
  if (Len > APP_TX_DATA_SIZE) {
      return USBD_FAIL;
  }
  
  // Critical Section only around memcpy and TransmitPacket to prevent race conditions
  __disable_irq();
  
  if (hcdc->TxState != 0){
      __enable_irq();
      return USBD_BUSY;
  }

  memcpy(UserTxBufferFS, Buf, Len);
  USBD_CDC_SetTxBuffer(&hUsbDeviceFS, UserTxBufferFS, Len);
  result = USBD_CDC_TransmitPacket(&hUsbDeviceFS);
  
  __enable_irq();
  /* USER CODE END 7 */
  return result;
}

